#!/usr/bin/env python3
"""The UI kit tool: one registry for the site's soft 3D (neumorphic) interface elements.

What : reads tools/website/ui_kit.json (style tokens for dark and light, and the selector lists for raised, primary, selected and
       pressable controls) and writes website/neumo.css, which every page loads last.
Why  : buttons were styled in a dozen stylesheets. Change a token or move a selector here, rerun, and every page follows.
Use  : python3 tools/website/ui_kit.py            write website/neumo.css
       python3 tools/website/ui_kit.py --list     print the UI element categories and which are centralised
       python3 tools/website/ui_kit.py --check    exit 1 if neumo.css differs from the registry
Then : python3 tools/website/bust_css.py, then the generators and sync_chrome.py (cache keys).
Find : tools/website/audit_buttons.js lists button-like elements on the live pages that no group covers.
Exit : 0 ok, 1 --check found a difference.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "website", "neumo.css")
HEAD = """/* neumo.css: GENERATED by tools/website/ui_kit.py from tools/website/ui_kit.json. Do not edit; change the registry and rerun.
 * One soft, raised (neumorphic) look for every control: a lit top-left edge, a dark drop at the bottom right, a pocket when pressed,
 * a pearl face when selected or primary. Brand colours only. Exempt from the token lint like brand.css. */
/* brand-lint: off */
"""
FOOT = """
/* the shape of a patch page's button (those pages load no other stylesheet) */
:where(.btn) { display: inline-flex; align-items: center; justify-content: center; min-height: 44px; padding: 0 24px; border-radius: 999px; font-weight: 600; text-decoration: none; white-space: nowrap; }
/* the copy control on code is always an icon: copy, then a tick for a moment */
html .copy { width: 36px; height: 36px; min-height: 0; padding: 0; gap: 0; justify-content: center; align-items: center; font-size: 0; }
html .copy > span { display: none; }
html .copy .ic { width: 18px; height: 18px; }
html .copy .ic-done, html .copy.done .ic-copy { display: none; }
html .copy.done .ic-done { display: block; color: var(--signal); }
html .dv-cmd .copy { width: 36px; padding: 0; }
/* the keycap: the old deep base layer goes, the top is the raised face */
html .ax-key { background: none; box-shadow: none; padding-bottom: 0; }
html .ax-key-top { color: var(--nm-ink); }
html .ax-key:hover .ax-key-top { transform: translateY(-1px); }
html .ax-key:active .ax-key-top { transform: translateY(1px); background: var(--nm-down); box-shadow: var(--nm-pocket); }
html .ax-key .ic { color: var(--signal); }
@media (prefers-reduced-motion: reduce) { html .btn, html .btn-ghost, html .icon-btn, html .ax-key-top { transition: none; } }
/* picture captions: one size and weight for the title on any picture (reel, bento, cards) */
html .ax-ttl, html .ax-bento-l, html .lib-card-title, html .nd-name, html .post-card h2 { font-size: var(--ui-t-media-title); font-weight: 600; line-height: 1.2; }
/* sliders: one look everywhere. A pocket groove, a pearl fill (set with --p by the page, else empty), a raised round thumb. */
html input[type=range] { -webkit-appearance: none; appearance: none; background: transparent; height: var(--ui-ctl-h-lg); cursor: pointer; }
html input[type=range]::-webkit-slider-runnable-track { height: var(--ui-sl-track); border-radius: 999px; background: var(--nm-pearl) 0 0 / max(var(--ui-sl-track), var(--p, 0%)) 100% no-repeat, var(--nm-down); box-shadow: var(--nm-pocket); }
html input[type=range]::-moz-range-track { height: var(--ui-sl-track); border-radius: 999px; background: var(--nm-down); box-shadow: var(--nm-pocket); }
html input[type=range]::-moz-range-progress { height: var(--ui-sl-track); border-radius: 999px; background: var(--nm-pearl); }
html input[type=range]::-webkit-slider-thumb { -webkit-appearance: none; width: var(--ui-sl-thumb); height: var(--ui-sl-thumb); margin-top: calc((var(--ui-sl-track) - var(--ui-sl-thumb)) / 2); border: 0; border-radius: 50%; background: var(--nm-up); box-shadow: var(--nm-raise); transition: transform 160ms ease; }
html input[type=range]::-moz-range-thumb { width: var(--ui-sl-thumb); height: var(--ui-sl-thumb); border: 0; border-radius: 50%; background: var(--nm-up); box-shadow: var(--nm-raise); }
html input[type=range]:hover::-webkit-slider-thumb { transform: scale(1.06); }
html input[type=range]:active::-webkit-slider-thumb { transform: scale(0.94); background: var(--nm-down); box-shadow: var(--nm-pocket); }
html input[type=range]:focus-visible { outline: 2px solid var(--signal); outline-offset: 2px; border-radius: 999px; }
/* brand-lint: on */
"""


def build(k):
    t = k["tokens"]
    var = lambda d: "".join("  --nm-%s: %s;\n" % (n, v) for n, v in d.items())
    h = lambda lst, suf="": ", ".join("html " + s + suf for s in lst)
    L = k["layout"]
    lay = "".join("  --ui-sp-%s: %s;\n" % kv for kv in L["space"].items())
    lay += "".join("  --ui-card-%s: %s;\n" % kv for kv in L["card"].items())
    lay += "".join("  --ui-ctl-%s: %s;\n" % kv for kv in L["control"].items())
    lay += "".join("  --ui-t-%s: %s;\n" % kv for kv in L["type"].items())
    lay += "".join("  --ui-sl-%s: %s;\n" % kv for kv in L["slider"].items())
    out = HEAD + ":root {\n" + lay + var(t["dark"]) + "}\nhtml:not([data-mode=\"midnight\"]) {\n" + var(t["light"]) + "}\n"
    if k.get("dark_surfaces"):   # surfaces that stay dark in both modes use the dark tokens inside them (none today: the pages switch with the mode)
        out += "\n" + ", ".join("html " + x for x in k["dark_surfaces"]) + " {\n" + var(t["dark"]) + "}\n"
    out += "\n/* raised: secondary buttons, icon buttons, arrows, tabs that are not selected */\n" + h(k["raised"]) + " {\n  background: var(--nm-up); color: var(--nm-ink); border: 0; box-shadow: var(--nm-raise); -webkit-backdrop-filter: none; backdrop-filter: none; opacity: 1;\n  transition: box-shadow 160ms ease, transform 160ms ease, background 160ms ease;\n}\n"
    out += h(k["pressable"], ":hover") + " { background: var(--nm-up); transform: translateY(-1px); }\n"
    out += "\n/* primary: a pearl face */\n" + h(k["primary"]) + " {\n  background: var(--nm-pearl); color: var(--nm-ink-on-pearl); border: 0; box-shadow: var(--nm-pearl-raise);\n  transition: box-shadow 160ms ease, transform 160ms ease, background 160ms ease;\n}\n"
    out += h(k["primary"][:3], ":hover") + " { background: var(--nm-pearl); transform: translateY(-1px); }\n"
    out += "\n/* selected or on: the same pearl face */\n" + h(k["selected"]) + " {\n  background: var(--nm-pearl); color: var(--nm-ink-on-pearl); box-shadow: var(--nm-pearl-raise);\n}\n"
    out += "\n/* pressed: sinks into a pocket */\n" + h(k["pressable"], ":active") + " {\n  transform: translateY(1px); background: var(--nm-down); color: var(--nm-ink); box-shadow: var(--nm-pocket);\n}\n"
    out += "\n/* pocket: inputs, code blocks and tags sit in a recess */\n" + h(k["pocket"]) + " {\n  background: var(--nm-down); box-shadow: var(--nm-pocket); border: 0;\n}\n"
    out += "\n/* cards: text cards are a raised face, picture cards only get the raised shadow so the picture stays whole */\n" + h(k["card_flat"]) + " {\n  background: var(--nm-up); box-shadow: var(--nm-raise); border: 0;\n}\n" + h(k["card_shadow"]) + " {\n  box-shadow: var(--nm-raise);\n}\n"
    out += "\n/* every card and panel shares one radius; text cards share one padding */\n" + h(k["card_flat"] + k["card_shadow"]) + " { border-radius: var(--ui-card-radius); }\n" + h(k["card_flat"]) + " { padding: var(--ui-card-pad); }\n"
    out += "\n/* mode switches (macOS / Windows / Linux, view toggles): no recess behind the buttons, the selected one is the pearl */\nhtml .tabs, html .seg, html .cmd-tabs { background: none; box-shadow: none; gap: var(--ui-sp-2); }\nhtml .tab-pill { display: none; }\n"
    return out + FOOT


def main():
    k = json.load(open(os.path.join(HERE, "ui_kit.json")))
    if "--list" in sys.argv:
        for c in k["catalog"]:
            print("%-32s %-8s %s\n%-32s %-8s %s" % (c["category"], {True: "central", False: "per page", "partly": "partly"}[c["central"]], c["where"], "", "", "e.g. " + c["what"]))
        return 0
    new = build(k)
    cur = open(OUT).read() if os.path.exists(OUT) else ""
    if "--check" in sys.argv:
        print("in sync" if cur == new else "neumo.css differs from the registry"); return 0 if cur == new else 1
    open(OUT, "w").write(new); print("wrote website/neumo.css (%d bytes)" % len(new)); return 0


if __name__ == "__main__":
    sys.exit(main())
