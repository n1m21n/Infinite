SCRIPT_FIXES = [
    ('document.getElementById("btn-audio").innerText = "Microphone on";', 'document.getElementById("btn-audio").classList.add("on");document.getElementById("btn-audio").setAttribute("aria-label","Microphone on");'),
    ('document.getElementById("btn-audio").innerText = "Microphone blocked";', 'document.getElementById("btn-audio").classList.add("off");document.getElementById("btn-audio").setAttribute("aria-label","Microphone blocked");'),
    ('"mic active"', '"Microphone on"'), ('"mic denied"', '"Microphone blocked"'),
    ('document.body.innerHTML = "webgl not supported";', 'document.body.innerHTML = \'<p class="fallback">This visual needs WebGL, which this browser does not offer.</p>\';'),
]


def build_widget(it):
    path = os.path.join(E, it["slug"] + ".html")
    if not os.path.exists(path):
        sys.exit(f"missing widget {path}")
    s = open(path, encoding="utf-8").read()
    i = s.find("<script>")
    if i < 0:
        sys.exit(f"no script in {path}")
    body = s[i:]
    for a, b in SCRIPT_FIXES:
        body = body.replace(a, b)
    head = (SHELL_HEAD.replace("@@TITLE@@", e(it["title"])).replace("@@DESC@@", e(it["description"]))
            .replace("@@URL@@", f"{BASE}embeds/{it['slug']}.html").replace("@@LD@@", ld(it)))
    return head + body


def ld(it):
    """CreativeWork JSON-LD for one widget, part of the embeds gallery. </ is escaped so the script tag cannot close early."""
    url = f"{BASE}embeds/{it['slug']}.html"
    return json.dumps({"@context": "https://schema.org", "@type": "CreativeWork", "name": it["title"], "description": it["description"],
                       "url": url, "image": BASE + "assets/og-image.jpg", "genre": "Audio-reactive visual", "isAccessibleForFree": True,
                       "author": {"@type": "Person", "name": "Naman Soni"},
                       "isPartOf": {"@type": "CollectionPage", "name": "Infinite embeds", "url": BASE + "embeds/"}},
                      ensure_ascii=False).replace("</", "<\\/")


def icon(name):
    """Brand glyph from art/icons/src, inlined so a pill needs no request."""
    svg = open(os.path.join(chrome.ROOT, "art", "icons", "src", name + "-20.svg"), encoding="utf-8").read().strip()
    return svg.replace("<svg ", '<svg class="ic" aria-hidden="true" ', 1).replace("\n", "")


