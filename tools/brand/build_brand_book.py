# ---------------------------------------------------------------- figures (SVG, computed)
def lem_path(A, cx, cy, n=240):
    pts = []
    for i in range(n + 1):
        p = 2 * math.pi * i / n
        d = 1 + math.cos(p) ** 2
        pts.append((cx + A * math.sin(p) / d, cy - A * math.sin(p) * math.cos(p) / d))
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "Z"


def grad_def(gid, x0, x1):
    g = C["gradient"]
    st = "".join(f'<stop offset="{p}" stop-color="{h}"/>' for h, p in zip(g["stops"], g["positions"]))
    return f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{x0}" y1="0" x2="{x1}" y2="0">{st}</linearGradient>'


def mark(A=100, pad=None, gid="g0"):
    s = B["logo"]["stroke"] * A
    w, h = 2 * A + s, A / math.sqrt(2) + s
    pad = s / 2 if pad is None else pad
    W, H = w + 2 * pad, h + 2 * pad
    return (f'<svg viewBox="0 0 {W:.1f} {H:.1f}" role="img" aria-label="Infinite mark"><defs>{grad_def(gid, pad, pad + w)}</defs>'
            f'<path d="{lem_path(A, W / 2, H / 2)}" fill="none" stroke="url(#{gid})" stroke-width="{s:.2f}" stroke-linejoin="round"/></svg>')


