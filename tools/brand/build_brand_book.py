# ---------------------------------------------------------------- contrast gate
def gate():
    rows, bad = [], []
    for mode, roles in MODES.items():
        for fgk, bgk, need in C["contrast_gate"]["pairs"]:
            f, b = roles[fgk], roles[bgk]
            r = K.wcag(f, b)
            lc = K.apca(f, b)
            ok = r >= need
            rows.append((mode, fgk, bgk, f, b, r, lc, need, ok))
            if not ok:
                bad.append(f"{mode}: {fgk} {f} on {bgk} {b} = {r:.2f}, needs {need}")
    return rows, bad


GATE, BAD = gate()
if BAD:
    print("contrast gate FAILED:\n  " + "\n  ".join(BAD))
    sys.exit(1)


# ---------------------------------------------------------------- springs
def spring(z, w, t):
    if z < 1:
        wd = w * math.sqrt(1 - z * z)
        return 1 - math.exp(-z * w * t) * (math.cos(wd * t) + z / math.sqrt(1 - z * z) * math.sin(wd * t))
    return 1 - (1 + w * t) * math.exp(-w * t)


def spring_stats(z, w):
    over = math.exp(-math.pi * z / math.sqrt(1 - z * z)) if z < 1 else 0.0
    t, dt, settle = 0.0, 0.0005, 0.0
    while t < 3:
        if abs(spring(z, w, t) - 1) > 0.02:
            settle = t
        t += dt
    return over, settle + dt


def css_linear(z, w, n=32):
    _, T = spring_stats(z, w)
    pts = [f"{spring(z, w, T * i / n):.3f}".rstrip("0").rstrip(".") or "0" for i in range(n + 1)]
    pts[-1] = "1"
    return f"linear({', '.join(pts)})", round(T * 1000)


SPRINGS = []
for s in B["motion"]["springs"]:
    o, st = spring_stats(s["zeta"], s["omega"])
    lin, ms = css_linear(s["zeta"], s["omega"])
    SPRINGS.append(dict(s, overshoot=o, settle_ms=ms, linear=lin, response=2 * math.pi / s["omega"]))


# ---------------------------------------------------------------- token files
def fluid(mn, mx, lo=375, hi=1440):
    if mn == mx:
        return f"{mn / 16:.4g}rem"
    slope = (mx - mn) / (hi - lo)
    base = mn - slope * lo
    return f"clamp({mn / 16:.4g}rem, {base / 16:.4g}rem + {slope * 100:.4g}vw, {mx / 16:.4g}rem)"


def slug(s):
    return s.lower().replace(" ", "-").replace(",", "")


def write_css():
    L = ["/* Generated by tools/brand/build_brand_book.py from docs/brand/brand.json. Do not edit. */",
         "/* Usage: <html data-mode=\"midnight|mist|paper\">; paper is the default. */"]
    for i, (mode, roles) in enumerate(MODES.items()):
        sel = ":root, [data-mode=\"paper\"]" if mode == "paper" else f"[data-mode=\"{mode}\"]"
        L.append(f"{sel} {{")
        L += [f"  --{k}: {v};" for k, v in roles.items() if not k.startswith("_")]
        L.append("}")
    L.append(":root {")
    for fam, pal in (("ember", C["anchors"]["ember"]), ("signal", C["anchors"]["signal"]), ("midnight", C["anchors"]["midnight"])):
        L += [f"  --{fam}-{k}: {v};" for k, v in pal.items()]
    g = C["gradient"]
    L.append(f"  --brand-gradient: linear-gradient(90deg, {', '.join(f'{h} {p * 100:g}%' for h, p in zip(g['stops'], g['positions']))});")
    L.append(f"  --iridescence: conic-gradient({', '.join(C['iridescence']['stops'])});")
    for c in C["category"]:
        L.append(f"  --cat-{slug(c['name'])}: {c['hex']};")
    for s in B["type"]["web_scale"]:
        fam = "'Geist Mono', ui-monospace, monospace" if "mono" in s["step"].lower() else "Geist, system-ui, sans-serif"
        L.append(f"  --type-{slug(s['step'])}: {s['weight']} {fluid(s['min'], s['max'])}/{s['leading']} {fam};")
        L.append(f"  --track-{slug(s['step'])}: {s['tracking']}em;")
    for r in B["shape"]["brand_radius"]:
        L.append(f"  --radius-{slug(r['name'])}: {r['px']}px;")
    for i, sp in enumerate(B["shape"]["space"]):
        L.append(f"  --space-{i + 1}: {sp}px;")
    for e in B["motion"]["eases"]:
        L.append(f"  --{e['name']}: {e['value']};")
    for s in SPRINGS:
        L.append(f"  --spring-{s['name']}: {s['linear']};")
        L.append(f"  --spring-{s['name']}-ms: {s['settle_ms']}ms;")
    for k, v in B["motion"]["durations_ms"].items():
        L.append(f"  --dur-{k}: {v}ms;")
    L.append("}")
    L.append("@media (prefers-reduced-motion: reduce) { :root { " + " ".join(f"--dur-{k}: 0ms;" for k in B["motion"]["durations_ms"]) + " } }")
    open(os.path.join(DOC, "brand.css"), "w").write("\n".join(L) + "\n")


def write_dtcg():
    def col(h):
        return {"$type": "color", "$value": {"colorSpace": "srgb", "components": [round(x, 4) for x in K.rgb(h)], "hex": h}}
    t = {"$description": "Infinite brand tokens (DTCG 2025.10). Generated from docs/brand/brand.json.",
         "mode": {m: {k: col(v) for k, v in r.items() if not k.startswith("_") and v.startswith("#")} for m, r in MODES.items()},
         "palette": {f: {k: col(v) for k, v in p.items()} for f, p in C["anchors"].items()},
         "category": {slug(c["name"]): col(c["hex"]) for c in C["category"]},
         "radius": {slug(r["name"]): {"$type": "dimension", "$value": {"value": r["px"], "unit": "px"}} for r in B["shape"]["brand_radius"]},
         "space": {str(s): {"$type": "dimension", "$value": {"value": s, "unit": "px"}} for s in B["shape"]["space"]},
         "duration": {k: {"$type": "duration", "$value": {"value": v, "unit": "ms"}} for k, v in B["motion"]["durations_ms"].items()},
         "easing": {e["name"]: {"$type": "cubicBezier", "$value": [float(x) for x in e["value"][13:-1].split(",")]} for e in B["motion"]["eases"]},
         "font": {slug(f["name"]): {"$type": "fontFamily", "$value": f["name"]} for f in B["type"]["families"] if f["weights"]}}
    json.dump(t, open(os.path.join(DOC, "brand.tokens.json"), "w"), indent=2)


def write_images():
    out = os.path.join(DOC, "img")
    os.makedirs(out, exist_ok=True)
    done = []
    try:
        from PIL import Image
    except ImportError:
        return done
    for p in sorted(glob.glob(os.path.join(ROOT, "art", "brand", "3d", "renders", "*.png"))):
        n = os.path.basename(p)[:-4]
        im = Image.open(p).convert("RGB")
        if im.width > 1600:
            im = im.resize((1600, round(im.height * 1600 / im.width)), Image.LANCZOS)
        im.save(os.path.join(out, n + ".webp"), quality=86, method=6)
        done.append(n)
    return done


