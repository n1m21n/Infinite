#!/usr/bin/env python3
"""Write the buyer's install-to-play steps (tools/installer/steps.json) into every place a buyer reads them.

  python3 tools/installer/sync_steps.py           rewrite the marked blocks
  python3 tools/installer/sync_steps.py --check   exit 1 if any block is out of date (preflight)

Targets: website/download.html (mac, windows, linux, play), website/plugin.html (plugin),
tools/installer/mac/resources/conclusion.html (after), tools/installer/windows/Infinite.iss
(Finished page), tools/installer/linux/install.sh (closing lines), worker/license/steps.js (key email).
Markup in steps.json: **bold** and `code`.
"""
import html, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
S = json.load(open(os.path.join(ROOT, "tools/installer/steps.json"), encoding="utf-8"))


def to_html(t):
    t = html.escape(t, quote=False)
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
    return re.sub(r"`(.+?)`", r"<code>\1</code>", t)


def to_text(t):
    return re.sub(r"\*\*(.+?)\*\*|`(.+?)`", lambda m: m.group(1) or m.group(2), t)


def ol(items, cls, indent="        "):
    rows = "".join(f"{indent}  <li>{i}</li>\n" for i in items)
    return f"{indent}<ol class=\"{cls}\">\n{rows}{indent}</ol>\n"


def html_block(name, body, indent="        "):
    return f"{indent}<!-- steps:{name} -->\n{body}{indent}<!-- /steps:{name} -->\n"


def replace_html(s, name, body, indent="        "):
    pat = re.compile(rf"[ \t]*<!-- steps:{name} -->\n.*?<!-- /steps:{name} -->\n", re.S)
    assert pat.search(s), f"marker steps:{name} missing"
    return pat.sub(lambda _: html_block(name, body, indent), s, count=1)


def replace_lines(s, begin, end, lines):
    pat = re.compile(rf"({re.escape(begin)}[^\n]*\n).*?({re.escape(end)}\n)", re.S)
    assert pat.search(s), f"marker {begin} missing"
    return pat.sub(lambda m: m.group(1) + "".join(l + "\n" for l in lines) + m.group(2), s, count=1)


def build():
    out = {}
    h = lambda k: [to_html(t) for t in S[k]]

    p = os.path.join(ROOT, "website/download.html")
    s = open(p, encoding="utf-8").read()
    for k in ("mac", "windows", "linux", "play"):
        s = replace_html(s, k, ol(h(k), "dl-steps"))
    out[p] = s

    p = os.path.join(ROOT, "website/plugin.html")
    s = open(p, encoding="utf-8").read()
    lead = '<a href="download.html">Download the installer</a> for your computer and open it. That page shows the one-time step your system asks for.'
    s = replace_html(s, "plugin", ol([lead] + h("play"), "plug-steps"))
    out[p] = s

    p = os.path.join(ROOT, "tools/installer/mac/resources/conclusion.html")
    s = open(p, encoding="utf-8").read()
    s = replace_html(s, "after", "<ol>\n" + "".join(f"<li>{i}</li>\n" for i in h("play")) + "</ol>\n", indent="")
    out[p] = s

    p = os.path.join(ROOT, "tools/installer/windows/Infinite.iss")
    s = open(p, encoding="utf-8").read()
    msg = "%n%n".join(f"{i + 1}. {to_text(t)}" for i, t in enumerate(S["play"]))
    msg = "Next:%n%n" + msg + "%n%n" + to_text(S["windows"][-1])
    s = replace_lines(s, "; steps:begin", "; steps:end", [f"FinishedLabelNoIcons={msg}", f"FinishedLabel={msg}"])
    out[p] = s

    p = os.path.join(ROOT, "tools/installer/linux/install.sh")
    s = open(p, encoding="utf-8").read()
    lines = []
    for i, t in enumerate(S["play"]):
        t = to_text(t).replace('"', '\\"').replace("$", "\\$")
        if i == 0:
            t = t.rstrip(".") + " (~/.vst3)."
        lines.append(f'say "  {i + 1}. {t}"')
    s = replace_lines(s, "# steps:begin", "# steps:end", lines)
    out[p] = s

    p = os.path.join(ROOT, "worker/license/steps.js")
    out[p] = ("// Generated by tools/installer/sync_steps.py from tools/installer/steps.json. Do not edit.\n"
              "export const STEPS = " + json.dumps({k: v for k, v in S.items() if k != "_"}, indent=2, ensure_ascii=False) + ";\n")
    return out


def main():
    check = "--check" in sys.argv
    stale = []
    for p, s in build().items():
        cur = open(p, encoding="utf-8").read() if os.path.exists(p) else ""
        if cur != s:
            stale.append(os.path.relpath(p, ROOT))
            if not check:
                open(p, "w", encoding="utf-8").write(s)
    if check and stale:
        print("install steps out of date (run tools/installer/sync_steps.py):", *stale, sep="\n  ")
        return 1
    print(("updated: " + ", ".join(stale)) if stale and not check else "install steps in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
