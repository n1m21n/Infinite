#!/usr/bin/env python3
"""Export the role critic (goal item 4) for Generate Samples: one MLP on frame_features.vector, trained on every render in gen_parts_v2.jsonl,
plus a cut-off per role, into src/app/graph/RoleCriticWeights.inc (read by RoleCritic.cpp).
    export_role_critic.py [--epochs 40] [--pct 3] [--calib-on shaped|all] [--inner 4] [--out FILE] [--check N]
Cut-offs are chosen as role_critic_render.py train chooses them (--calib oof): every style is scored once by a model that never saw it
(--inner folds by style), and the cut-off is the --pct percentile of P(declared role) on those out-of-fold scores (--calib-on rows only).
The shipped model then trains on all rows. --check N writes N rows' vectors and the shipped model's probabilities to a JSON file next to
the .inc's tool output, so the C++ port can be compared with it (critic_parity.py)."""
import argparse, json, os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import frame_features as ff
from role_critic_samples import MLP
from role_critic_render import OUT as ROWS
INC = os.path.join(HERE, "../../src/app/graph/RoleCriticWeights.inc")

def arr(name, a):
    a = np.asarray(a, np.float32).ravel()
    body = ",\n".join("      " + ", ".join("%.7gf" % v for v in a[i:i + 8]) for i in range(0, len(a), 8))
    return "   constexpr float %s[%d] = {\n%s,\n   };\n" % (name, len(a), body)

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--epochs", type=int, default=40); ap.add_argument("--pct", type=float, default=3)
    ap.add_argument("--calib-on", choices=["shaped", "all"], default="shaped"); ap.add_argument("--inner", type=int, default=4); ap.add_argument("--out", default=INC)
    ap.add_argument("--check", type=int, default=0); a = ap.parse_args()
    rows = [json.loads(l) for l in open(ROWS)]
    X = np.nan_to_num(np.array([ff.vector(r) for r in rows])); names = sorted({r["role"] for r in rows}); y = np.array([names.index(r["role"]) for r in rows])
    styles = sorted({r["id"] for r in rows}); g = np.array([styles.index(r["id"]) for r in rows]); shaped = np.array([bool(r.get("dots")) for r in rows])
    mu, sd = X.mean(0), X.std(0) + 1e-9; Z = (X - mu) / sd
    wt = lambda m: (1.0 / np.maximum(np.bincount(y[m], minlength=len(names)), 1))[y[m]]
    rng = np.random.default_rng(0); inner = {s: i % a.inner for i, s in enumerate(rng.permutation(len(styles)))}; fold = np.array([inner[s] for s in g])
    P = np.zeros((len(y), len(names)))
    for k in range(a.inner):
        fit = fold != k; P[~fit] = MLP(len(names), a.epochs, h=(128, 64), seed=200 + k).fit(Z[fit], y[fit], wt(fit)).proba(Z[~fit])
        print("out-of-fold", k, flush=True)
    cm = shaped if a.calib_on == "shaped" else np.ones(len(y), bool)
    th = np.array([np.percentile(P[cm & (y == c), c], a.pct) for c in range(len(names))])
    M = MLP(len(names), a.epochs, h=(128, 64), seed=0).fit(Z, y, wt(np.ones(len(y), bool)))
    print("cut-offs", dict(zip(names, np.round(th, 4))))
    (W1, b1), (W2, b2), (W3, b3) = M.p
    src = ("// Generated by tools/universe/export_role_critic.py from %d renders of the live generator (%d dot-shaped), %d styles.\n"
           "// Role critic: frame_features.vector (%d numbers) -> standardise -> %d ReLU -> %d ReLU -> %d roles (softmax).\n"
           "// Cut-off per role: the %g percentile of P(declared role), out-of-fold by style, on %s renders.\n#pragma once\n\nnamespace RoleCriticData\n{\n"
           % (len(y), int(shaped.sum()), len(styles), X.shape[1], W1.shape[1], W2.shape[1], len(names), a.pct, a.calib_on))
    src += "   constexpr int kIn = %d, kH1 = %d, kH2 = %d, kRoles = %d;\n" % (X.shape[1], W1.shape[1], W2.shape[1], len(names))
    src += "   constexpr const char* kRoleNames[kRoles] = { %s };\n" % ", ".join('"%s"' % n for n in names)
    for n, v in (("kMean", mu), ("kScale", sd), ("kCut", th), ("kW1", W1), ("kB1", b1), ("kW2", W2), ("kB2", b2), ("kW3", W3), ("kB3", b3)): src += arr(n, v)
    src += "}\n"; open(a.out, "w").write(src); print("->", a.out, len(src) // 1024, "KB")
    if a.check:
        ix = np.random.default_rng(1).choice(len(rows), a.check, replace=False)
        json.dump({"roles": names, "rows": [{"seed": rows[i]["seed"], "style": rows[i]["style"], "part": rows[i]["part"], "x": X[i].tolist(),
                   "p": M.proba(Z[i:i + 1])[0].tolist()} for i in ix]}, open(os.path.join(HERE, "../../build-wasm/role_critic_check.json"), "w"))

if __name__ == "__main__":
    main()
