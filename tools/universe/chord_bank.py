#!/usr/bin/env python3
"""Generate Samples' weighted progression bank: the owner's library (kNoteProgs) plus the four-bar windows real songs use most,
weighted by how often songs use them. Only the counts ship, as bare degrees. A count table tied the GRU on held-out songs, so
this is the model (docs/plans/data-universe/feel/chord_model.json).
    ~/Infinite/ml-venv/bin/python3 -I tools/universe/chord_bank.py
Scores five held-out splits, then writes src/app/graph/GenerateSamplesChords.inc from every song."""
import collections, json, math, os, random, re
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "../../src/app/graph")
TOP, TEMPER = 300, 0.5
rows = [json.loads(l) for l in open(os.path.expanduser("~/Infinite/training-data/store/chord_windows.jsonl"))]
inc = open(os.path.join(SRC, "GenerateSamplesNotes.inc")).read()
OWNER = {0: [], 1: []}
for m, _, *d in re.findall(r"\{\s*(\d)\s*,\s*(\d+)\s*,\s*\{\s*(\d)\s*,\s*(\d)\s*,\s*(\d)\s*,\s*(\d)\s*\}", inc.split("kNoteProgs")[1].split("};")[0]):
    OWNER[int(m)].append(tuple(int(x) for x in d))
def collect(songs, fam):
    c = collections.Counter()
    for r in songs:
        if r["minor"] == fam:
            for x, n in r["w"]:
                c[tuple(x)] += 1
    return c
def bank(c, fam):
    keep = list(OWNER[fam]) + [k for k, _ in c.most_common() if len(set(k)) > 1 and k not in OWNER[fam]][:TOP]
    return {k: max(1, round(c[k] ** TEMPER)) for k in keep}
def score(b, test):
    n, tot = sum(test.values()), sum(b.values())
    bits = -sum(v * math.log2(0.999 * b.get(k, 0) / tot + 0.001 / 2394) for k, v in test.items()) / n
    return bits, sum(v for k, v in test.items() if k in b) / n
songs = sorted({r["song"] for r in rows})
res = {"new": [], "old": []}
for seed in range(5):
    random.Random(seed).shuffle(songs); te = set(songs[:len(songs) // 5])
    for fam in (0, 1):
        tr, ts = collect([r for r in rows if r["song"] not in te], fam), collect([r for r in rows if r["song"] in te], fam)
        res["new"].append(score(bank(tr, fam), ts)); res["old"].append(score({k: 1 for k in OWNER[fam]}, ts))
out = {k: {"bits": sum(x[0] for x in v) / len(v), "coverage": sum(x[1] for x in v) / len(v)} for k, v in res.items()}
print(out)
json.dump(out, open(os.path.join(HERE, "../../docs/plans/data-universe/feel/chord_bank.json"), "w"), indent=1)
lines = ["// Generated by tools/universe/chord_bank.py: the owner's progressions plus the four-bar windows real songs use most.",
         "// minor: 0 major family, 1 minor family. weight: how often songs use it, tempered, so a pick follows real use.",
         "// Do not edit by hand: rerun the tool.", "struct ChordProg { int minor, weight; int d[4]; };", "static const ChordProg kChordProgs[] = {"]
for fam in (0, 1):
    for k, w in bank(collect(rows, fam), fam).items():
        lines.append("   { %d, %d, { %d, %d, %d, %d } }," % (fam, w, *k))
open(os.path.join(SRC, "GenerateSamplesChords.inc"), "w").write("\n".join(lines + ["};", ""]))
