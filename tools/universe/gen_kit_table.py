#!/usr/bin/env python3
"""refs/kits.json (kit_scan.py) -> src/app/graph/GenerateSamplesKits.inc: per style, the drum lane settings that move the bundled
kit toward the genre's real hits. Decay is the lane's one-pole time constant over the sample's own length (-30 dB time / 3.45);
kick pitch is semitones from the bundled kick's body; kick transient follows the real kick's click (spectral centroid).
Styles with no measured pack take their family's median; a family with none is left out (the engine keeps its old draw)."""
import json, math, os, re, statistics
import soundfile as sf
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
K = json.load(open(os.path.join(ROOT, "internal/plans/generate-samples/refs/kits.json")))
KIT = os.path.join(ROOT, "assets/drumkits/infinite-basic")
length = {n: sf.info(os.path.join(KIT, n + ".wav")).duration for n in ("01-kick", "02-snare", "05-clap")}
base = K["bundled_kit"]
fam = {}
for m in re.finditer(r'^\s*\{ "([a-z0-9_]+)", "[^"]*", "([a-z0-9_]+)"', open(os.path.join(ROOT, "src/app/graph/GenerateSamplesTables.inc")).read(), re.M):
    fam[m[1]] = m[2]
def med(style, role, key):
    return K["styles"].get(style, {}).get(role, {}).get(key, {}).get("median")
def row(style):
    return {"kd": med(style, "kick", "decay_ms"), "kp": med(style, "kick", "pitch_hz"), "kc": med(style, "kick", "centroid_hz"), "sd": med(style, "snare", "decay_ms")}
rows = {}
for s in fam:
    r = row(s)
    if None in r.values():
        peers = [row(p) for p in K["styles"] if fam.get(p) == fam[s]]
        peers = [p for p in peers if None not in p.values()]
        if not peers:
            continue
        r = {k: statistics.median(p[k] for p in peers) for k in r}
    rows[s] = r
out = ["// Generated by tools/universe/gen_kit_table.py from refs/kits.json (tools/universe/kit_scan.py). Do not edit.", "",
       "struct GenKit { const char* id; float kickDecay, snareDecay, kickSemis, kickTransient; };", "static const GenKit kGenKits[] = {"]
for s, r in sorted(rows.items()):
    tau = lambda ms, n: min(1.0, (ms / 3.45 / 1000.0) / length[n])
    semis = 12 * math.log2(max(30.0, r["kp"]) / base["01-kick"]["pitch_hz"])
    tr = max(0.0, min(0.9, math.log2(max(r["kc"], 190.0) / 190.0) / 4.0))
    out.append('   { "%s", %.3ff, %.3ff, %.2ff, %.2ff },' % (s, tau(r["kd"], "01-kick"), tau(r["sd"], "02-snare"), semis, tr))
out.append("};")
open(os.path.join(ROOT, "src/app/graph/GenerateSamplesKits.inc"), "w").write("\n".join(out) + "\n")
print(len(rows), "styles;", {k: round(v, 3) for k, v in length.items()})
