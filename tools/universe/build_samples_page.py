#!/usr/bin/env python3
"""Publish the sample library as the website's Samples page.
    build_samples_page.py [--lib ~/Infinite/patch-universe-library/samples] [--site <repo>/website/samples]
Writes <site>/index.html (the blog page's chrome around the samples markup), data.json (codename, tags, peaks, media paths) and media/<id>/...
Audio becomes AAC (.m4a), posters become JPEG; patch.inf is kept so a sample can be opened in Infinite. media/ is gitignored (large)."""
import argparse, hashlib, json, os, re, shutil, subprocess, wave
import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ADJ = "amber cobalt velvet static hollow lunar paper neon quiet copper glass ember mossy tidal bright drift polar fuzzy brass silent plush rapid sandy electric woven lucid".split()
NOUN = "tide kiln orbit lantern ribbon engine meadow signal harbor prism garden cinder comet loom echo canyon pulse quarry lagoon thicket beacon fable marble drizzle atlas".split()


def codename(sid):
    h = int(hashlib.sha1(sid.encode()).hexdigest(), 16)
    return "%s %s %02d" % (ADJ[h % len(ADJ)].title(), NOUN[(h >> 8) % len(NOUN)].title(), (h >> 16) % 100)


def peaks(wav, n=120):
    w = wave.open(wav)
    d = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(float) / 32768
    if w.getnchannels() > 1:
        d = d.reshape(-1, w.getnchannels()).mean(axis=1)
    if not len(d):
        return [0.0] * n
    seg = np.array_split(np.abs(d), n)
    p = np.array([s.max() if len(s) else 0 for s in seg])
    return [round(float(x), 3) for x in p / max(p.max(), 1e-6)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lib", default=os.path.expanduser("~/Infinite/patch-universe-library/samples"))
    ap.add_argument("--site", default=os.path.join(ROOT, "website", "samples"))
    a = ap.parse_args()
    media = os.path.join(a.site, "media")
    shutil.rmtree(media, ignore_errors=True)
    out = []
    for l in open(os.path.join(a.lib, "index.jsonl")):
        m = json.loads(l)
        src = os.path.join(a.lib, m["id"])
        if not os.path.isdir(src):
            continue
        sid = m["id"].replace("/", "-")
        d = os.path.join(media, sid)
        os.makedirs(d, exist_ok=True)
        s = {"id": sid, "name": codename(sid), "kind": m["kind"], "tags": m.get("tags", []), "nodes": len(m.get("nodes", [])),
             "genome": m["genome"], "family": m.get("family"), "peaks": [0.0] * 120, "audio": None, "video": None, "poster": None,
             "patch": "media/%s/patch.inf" % sid}
        shutil.copy(os.path.join(src, "patch.inf"), d)
        wav = os.path.join(src, "sample.wav")
        if os.path.exists(wav):
            s["peaks"] = peaks(wav)
            subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", "128000", wav, os.path.join(d, "sample.m4a")], check=True)
            s["audio"] = "media/%s/sample.m4a" % sid
        mp4 = os.path.join(src, "preview.mp4")
        if os.path.exists(mp4):
            shutil.copy(mp4, os.path.join(d, "preview.mp4")); s["video"] = "media/%s/preview.mp4" % sid
            if m["kind"] == "AV":
                s["audio"] = None
            png = os.path.join(src, "poster.png")
            if os.path.exists(png):
                subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", png, "-vf", "scale=960:-2", "-q:v", "4", os.path.join(d, "poster.jpg")], check=True)
                s["poster"] = "media/%s/poster.jpg" % sid
        out.append(s)
    json.dump({"samples": out}, open(os.path.join(a.site, "data.json"), "w"), separators=(",", ":"))

    t = open(os.path.join(ROOT, "website", "blog", "index.html"), encoding="utf-8").read()
    t = t.replace('<body class="blog-page blog-index">', '<body class="blog-page">')
    t = re.sub(r"<title>.*?</title>", "<title>Infinite samples: generated patches you can hear</title>", t, count=1)
    desc = "Sounds and pictures made by patches that Infinite generated by itself. Swipe, listen, rate, and download the patch."
    t = re.sub(r'(<meta name="description" content=")[^"]*', r"\g<1>" + desc, t)
    t = re.sub(r'(<meta property="og:description" content=")[^"]*', r"\g<1>" + desc, t)
    t = re.sub(r'(<meta name="twitter:description" content=")[^"]*', r"\g<1>" + desc, t)
    t = t.replace("https://infinitedevices.org/blog/\"", "https://infinitedevices.org/samples/\"")
    t = re.sub(r'<script type="application/ld\+json">.*?</script>\s*', "", t)
    t = t.replace('href="../', 'href="../').replace('<link rel="stylesheet" href="../blog.css', '<link rel="stylesheet" href="samples.css?v=1">\n  <link rel="stylesheet" href="../blog.css')
    main = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "samples_main.html"), encoding="utf-8").read()
    t = re.sub(r"<main>.*?</main>", lambda _: main, t, count=1, flags=re.S)
    t = re.sub(r'<script src="\.\./blog\.js[^"]*" defer></script>', '<script src="samples.js?v=1" defer></script>', t)
    t = t.replace('<script src="../deck.js?v=5" defer></script>', "")
    open(os.path.join(a.site, "index.html"), "w", encoding="utf-8").write(t)
    print("%d samples -> %s" % (len(out), a.site))


if __name__ == "__main__":
    main()
