#!/usr/bin/env python3
"""Publish the sample library as the website's Samples page.
    build_samples_page.py [--lib ~/Infinite/patch-universe-library/samples] [--site <repo>/website/samples]
Writes <site>/index.html (the library page's deck chrome, fed by ../samples.js), data.json (codename, tags, peaks, media paths) and media/<id>/...
The data and media come from tools/catalog (wav / mp4 downloads, never the patch); this script only writes the page chrome."""
import argparse, os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "catalog"))
import catalog

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lib", default=os.path.expanduser("~/Infinite/patch-universe-library/samples"))
    ap.add_argument("--site", default=os.path.join(ROOT, "website", "samples"))
    ap.add_argument("--chrome-only", action="store_true", help="write only index.html (data and media come from catalog.py all)")
    a = ap.parse_args()
    if not a.chrome_only:
        catalog.publish_samples(a.lib, a.site)

    web = os.path.join(ROOT, "website")
    desc = "Sounds and pictures made by patches that Infinite generated by itself. Play them and download the sound or the clip."

    def chrome(src, depth, url, title):
        """The site's page chrome around new content: paths re-based, SEO block and the digit bird dropped, meta rewritten."""
        t = open(os.path.join(web, src), encoding="utf-8").read()
        t = re.sub(r"<!-- seo:start -->.*?<!-- seo:end -->", "", t, flags=re.S)
        t = re.sub(r'\s*<link rel="alternate"[^>]*catalog[^>]*>', "", t)
        t = re.sub(r'\s*<script type="application/ld\+json">.*?</script>', "", t, flags=re.S)
        t = re.sub(r'\s*<script src="[^"]*bird\.js[^"]*"[^>]*></script>', "", t)
        # library.html lives at the site root, embeds/index.html one level down; re-base both to the page's depth
        lift = depth - (1 if src.startswith("embeds/") else 0)
        if lift > 0:
            t = re.sub(r'\b(href|src)="(?!https?:|//|/|#|data:|mailto:|javascript:)', lambda m: m.group(1) + '="' + "../" * lift, t)
        t = re.sub(r"<link rel=\"canonical\" href=\"[^\"]*\"", '<link rel="canonical" href="%s"' % url, t)
        t = re.sub(r'(<meta property="og:url" content=")[^"]*', lambda m: m.group(1) + url, t)
        t = re.sub(r"<title>.*?</title>", "<title>%s</title>" % title, t, count=1)
        t = re.sub(r'(<meta (?:name="description"|property="og:description"|name="twitter:description") content=")[^"]*', lambda m: m.group(1) + desc, t)
        t = re.sub(r'(<meta (?:property="og:title"|name="twitter:title") content=")[^"]*', lambda m: m.group(1) + "Infinite samples", t)
        t = t.replace(' aria-current="page"', "")
        t = t.replace('<a href="%ssamples/">' % ("../" * (depth)), '<a href="%ssamples/" aria-current="page">' % ("../" * depth))
        return t

    # pictures are no longer on this page: the old address forwards to the list
    os.makedirs(os.path.join(a.site, "visuals"), exist_ok=True)
    open(os.path.join(a.site, "visuals", "index.html"), "w", encoding="utf-8").write('<!doctype html><meta charset="utf-8"><title>Infinite samples</title><meta name="robots" content="noindex"><link rel="canonical" href="https://infinitedevices.org/samples/"><meta http-equiv="refresh" content="0;url=../"><a href="../">Samples</a>\n')

    # Only audio: the list
    t = chrome("library.html", 1, "https://infinitedevices.org/samples/", "Infinite samples: generated sounds you can hear")
    main = """<main>
    <section class="section lib-hero">
      <div class="container smp-wrap">
        <h1 class="slab deck-title" style="text-align:center">Samples</h1>
        <div class="smp-bar">
          <span class="grow"></span>
          <button type="button" class="lib-icon-pill lib-shuffle-btn" id="smp-shuffle" aria-label="Shuffle" title="Shuffle"><svg class="lib-ic" viewBox="0 0 20 20" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M4 10V9a3 3 0 0 1 3-3h8M12.5 3.5 15 6l-2.5 2.5M16 10v1a3 3 0 0 1-3 3H5M7.5 11.5 5 14l2.5 2.5"/></svg></button>
        </div>
        <div class="smp-list" id="smp-list"></div>
        <div class="smp-pager" id="smp-pager" hidden>
          <button type="button" class="lib-icon-pill" data-pg="-1">Previous</button>
          <span class="smp-pg-info"></span>
          <button type="button" class="lib-icon-pill" data-pg="1">Next</button>
        </div>
        <p class="lib-empty" id="smp-empty" hidden>Nothing here yet.</p>
      </div>
    </section>
  </main>"""
    t = re.sub(r"<main>.*?</main>", lambda _: main, t, count=1, flags=re.S)
    t = re.sub(r'<script src="\.\./library\.js[^"]*"></script>', '<script src="../samples.js?v=12"></script>', t)
    t = re.sub(r'<script src="\.\./(?:\.\./)?deck\.js[^"]*"></script>', "", t)
    t = t.replace('</head>', '  <link rel="stylesheet" href="../samples.css?v=10">\n</head>', 1)
    open(os.path.join(a.site, "index.html"), "w", encoding="utf-8").write(t)
    print("pages ->", a.site)


if __name__ == "__main__":
    main()
