#!/usr/bin/env python3
"""Writes src/app/graph/GenerateSamplesTables.inc: the 34 music style cards (tools/catalog/styles_music.json) and,
for every node type a style can place, its seedable param rows and pins (tools/universe/describe_all.json).
The Generate Samples node compiles a style into a patch from these tables, so the app needs neither file at run time.
    gen_sample_tables.py [--check]     --check: exit 1 if the checked-in file is stale"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "src", "app", "graph", "GenerateSamplesTables.inc")
FIXED = ["Drum Sequencer", "Note Sequencer", "Chorder", "Arpeggiator", "Mixer", "Reverb", "Limiter", "Dynamics", "Piano", "String", "Wind"]
MOD_KEYS = ("cutoff", "position", "res", "mix", "detune", "drive", "warp", "size", "tone", "depth", "rate", "feedback")
LANES = ["kick", "snare", "chat", "ohat", "clap", "tom", "htom", "bell"]


def c(s):
    return json.dumps(s)  # a JSON string is a valid C string literal for these ASCII names


def lst(xs):
    return c(",".join(str(x) for x in xs))


def num(v):
    s = "%.6g" % float(v)
    return s + ("" if "." in s or "e" in s else ".0") + "f"   # -9f is not a C++ literal; -9.0f is


def build():
    styles = json.load(open(os.path.join(ROOT, "tools", "catalog", "styles_music.json")))["styles"]
    types = {t["type"]: t for t in json.load(open(os.path.join(HERE, "describe_all.json")))["types"]}
    used = set(FIXED)
    for s in styles:
        used |= set(s["synth"]) | set(s["fx"]) | set(s.get("notefx", []))
        if s.get("motif"):
            used |= set(s["motif"]["synth"]) | set(s["motif"].get("notefx", []))
    missing = sorted(n for n in used if n not in types)
    if missing:
        sys.exit("describe_all.json has no %s: re-run Infinite --describe --json tools/universe/describe_all.json" % missing)
    o = ["// Generated by tools/universe/gen_sample_tables.py from tools/catalog/styles_music.json and",
         "// tools/universe/describe_all.json. Do not edit; re-run the tool.", ""]
    o.append("static const GenStyle kGenStyles[] = {")
    for s in styles:
        ch, mo = s.get("chords") or {}, s.get("motif") or {}
        drums = ", ".join(c(s["drums"].get(l, "") or "") for l in LANES)
        o.append("   { %s, %s, %s, %d, %d, %s, %s, { %s }, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s," % (
            c(s["id"]), c(s["id"].replace("_", " ")), c(s["family"]), s["bpm"][0], s["bpm"][1], num(s["swing"]), lst(s["scale"]), drums,
            c(s["bass"]), lst(s["fx"]), lst(s["synth"]), lst(s["ban"]), num(s["mod"]), "true" if s.get("sidechain") else "false",
            lst(s.get("notefx", [])), num(s.get("groove", 0.5)), num(s.get("fill", 0.5)), num(s.get("gain", -9.0)), num(s.get("trim", 0.0))))
        o.append("     %s, %s, %s, %d, %s, %s," % ("true" if "chords" in s else "false", lst(ch.get("size", [3, 4])), num(ch.get("beats", 4.0)),
                                                  ch.get("steps", 4), num(ch.get("strum", 15.0)), num(ch.get("human", 0.0))))
        o.append("     %s, %s, %s, %d, %s, %s, %d, %s, %s }," % ("true" if mo else "false", lst(mo.get("synth", [])), num(mo.get("density", 0.5)),
                                                             mo.get("octave", 2), num(mo.get("gate", 60)), num(mo.get("gain", -11.0)), mo.get("range", 6),
                                                             num(mo.get("rate", 0.25)), lst(mo.get("notefx", []))))
    o.append("};")
    o.append("")
    o.append("static const GenType kGenTypes[] = {")
    for n in sorted(used):
        t = types[n]
        note = next((i["slot"] for i in t["inputs"] if i["kind"] == "note"), -1)
        audio = [i["slot"] for i in t["inputs"] if i["kind"] == "audio"]
        o.append("   { %s, %s, %d, %s }," % (c(n), c(t["category"]), note, lst(audio)))
    o.append("};")
    o.append("")
    o.append("static const GenRow kGenRows[] = {")
    for n in sorted(used):
        t = types[n]
        mods = {m["key"]: m for m in t["modulatable"] if m.get("key")}
        for r in t["rows"]:
            if not r.get("ui", True) or r["tag"] not in ("f", "i", "b"):
                continue
            lo, hi = r.get("min"), r.get("max")
            lo, hi = (0 if lo is None else lo), (1 if hi is None else hi)
            m = mods.get(r["key"])
            moves = bool(m) and not m.get("bool") and any(w in r["key"].lower() for w in MOD_KEYS)
            o.append("   { %s, %s, '%s', %s, %s, %d, %s }," % (c(n), c(r["key"]), r["tag"], num(lo), num(hi), len(r.get("options") or []),
                                                          "true" if moves else "false"))
    o.append("};")
    return "\n".join(o) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ""
        if old != text:
            sys.exit("GenerateSamplesTables.inc is stale: run tools/universe/gen_sample_tables.py")
        return
    open(OUT, "w").write(text)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), text.count("\n")))


if __name__ == "__main__":
    main()
