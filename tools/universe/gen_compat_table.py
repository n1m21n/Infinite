#!/usr/bin/env python3
"""Writes src/app/graph/GenerateSamplesCompat.inc: the kit compatibility models (compat_model.py) and the bundled kit's
sounds measured the way sound_features.py measures every pack sound, so the engine can score a kit it is about to build.
    ~/Infinite/media/.ytvenv/bin/python3 -I tools/universe/gen_compat_table.py
Per bundled drum lane (kick, snare, closed hat) the Drum Sequencer's own playback is simulated on a grid and measured:
  pitch -12..+12 semis (resampled, rate 2^(s/12), as the sequencer plays it)
  decay  the lane knob: a one-pole whose time constant is decay x the sample's length (1 = played out)
  transient -1 / 0 / 1: the attack ramp (40 / 3 / 0.5 ms) and the +4 dB boost that fades over 15 ms
The engine interpolates the grid. The 32 bands are stored per pitch and decay (a short decay
moves a kick's band shares a lot); the transient's effect on them is left out (the script prints how large it is).
Only role pairs the model table marks ok are exported; a weak pair is absent and the engine keeps the genre prior there."""
import json, math, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import audio_features as af  # noqa: E402
import sound_features as sf  # noqa: E402
import pairs as pr  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
KIT = os.path.join(ROOT, "assets/drumkits/infinite-basic")
LANES = [("kick", "01-kick"), ("snare", "02-snare"), ("hat", "03-closed-hat")]
SEMIS = list(range(-12, 13))
DECAYS = [0.03, 0.05, 0.08, 0.12, 0.18, 0.25, 0.35, 0.5, 0.65, 0.8, 0.9, 1.0]
TRANS = [-1.0, 0.0, 1.0]
SC = ["attack_ms", "decay_ms", "centroid_hz", "crest_db", "noise", "low", "mid", "high"]


def play(x, s, d, tr):
    """the Drum Sequencer's voice for one hit: resample, attack ramp + boost, one-pole decay (DrumSequencerNode.cpp)"""
    fs = af.FS
    n = x.shape[1]
    rate = 2.0 ** (s / 12.0)
    pos = np.arange(0.0, n - 1, rate)
    y = np.stack([np.interp(pos, np.arange(n), c) for c in x])
    t = np.arange(y.shape[1]) / fs
    att = (3.0 + (0.5 - 3.0) * tr) if tr >= 0 else (3.0 + (40.0 - 3.0) * -tr)
    g = np.minimum(1.0, (np.arange(y.shape[1]) + 1) / max(1, int(att * 0.001 * fs)))
    if tr > 0:
        g = g * (1.0 + (10 ** (tr * 4.0 / 20) - 1.0) * np.exp(-t / 0.015))
    if d < 0.999:
        g = g * np.exp(-t / max(0.005, d * n / fs))
    return y * g


def lane_grid(role, name):
    x = af.decode(os.path.join(KIT, name + ".wav"), 30.0)
    pitch, bands, grid = [], [], []
    drift = 0.0
    for s in SEMIS:
        base = sf.measure_array(play(x, s, 1.0, 0.0), role)
        pitch.append(base["pitch"])
        bands.append(base["bands"])
        row, brow = [], []
        for d in DECAYS:
            cell = []
            brow.append(sf.measure_array(play(x, s, d, 0.0), role)["bands"])
            for tr in TRANS:
                m = sf.measure_array(play(x, s, d, tr), role)
                drift = max(drift, float(np.abs(np.asarray(m["bands"]) - np.asarray(brow[-1])).sum()))
                cell.append([m[k] for k in SC])
            row.append(cell)
        grid.append(row)
        bands[-1] = brow
    print("%-6s pitch %s..%s  band drift over transient (L1, of 2.0): %.3f" % (role, pitch[0], pitch[-1], drift))
    return {"pitch": pitch, "bands": bands, "grid": grid}


PARITY = [((0, 0, 0.5), (1, 0, 0.25)), ((0, -3, 0.12), (2, 2, 0.35)), ((1, 4, 0.8), (2, -5, 0.05))]


def cell(g, role, s, d):
    sc = g["grid"][SEMIS.index(s)][DECAYS.index(d)][TRANS.index(0.0)]
    r = dict(zip(SC, sc))
    r["pitch"] = g["pitch"][SEMIS.index(s)]
    r["bands"] = g["bands"][SEMIS.index(s)][DECAYS.index(d)]
    return r


def score(m, x):
    raw = m["offset"]
    for t in m["trees"]:
        i = 0
        while t["f"][i] >= 0:
            i = t["l"][i] if np.float32(x[t["f"][i]]) <= np.float32(t["t"][i]) else t["r"][i]
        raw += m["rate"] * t["v"][i]
    return 1.0 / (1.0 + math.exp(-raw))


def flt(v, fmt="%.6g"):
    v = float(v)
    if not math.isfinite(v):
        v = 3.0e38 if v > 0 else -3.0e38
    t = fmt % v
    return t + (".0f" if not any(c in t for c in ".e") else "f")


def arr(name, vals, typ="float", fmt=flt):
    body = ",".join(fmt(v) if typ == "float" else str(int(v)) for v in vals)
    return "static const %s %s[] = {%s};\n" % (typ, name, body)


def main():
    cj = json.load(open(os.path.join(ROOT, "internal/plans/generate-samples/refs/compat.json")))
    assert cj["features"] == pr.NAMES, "feature list changed: re-run compat_model.py"
    out = ["// Generated by tools/universe/gen_compat_table.py from compat_model.py (kit compatibility, statistics only).\n",
           "// Do not edit by hand.\n", "#pragma once\n", "namespace compat {\n"]
    out.append("constexpr int kFeat = %d, kSemis = %d, kDecays = %d, kTrans = %d, kScal = %d;\n" % (len(pr.NAMES), len(SEMIS), len(DECAYS), len(TRANS), len(SC)))
    out.append(arr("kDecayGrid", DECAYS) + arr("kTransGrid", TRANS))
    grids = []
    for i, (role, name) in enumerate(LANES):
        g = lane_grid(role, name)
        grids.append(g)
        out.append(arr("kLane%dPitch" % i, [(-1000.0 if p is None else p) for p in g["pitch"]]))
        out.append(arr("kLane%dBands" % i, [v for r in g["bands"] for b in r for v in b]))
        out.append(arr("kLane%dGrid" % i, [v for r in g["grid"] for c in r for cell in c for v in cell]))
    # models: every tree's nodes flattened; per model the tree count, offset and rate, per tree its node start
    pairs = []
    for k, p in cj["pairs"].items():
        if p.get("weak") or "run" not in p or "check" not in p:  # weak: the engine keeps the genre prior
            continue
        pairs.append(k)
        for which in ("run", "check"):
            m = p[which]
            F, T, L, R, V, S = [], [], [], [], [], []
            for t in m["trees"]:
                S.append(len(F))
                F += t["f"]; T += t["t"]; L += t["l"]; R += t["r"]; V += t["v"]
            tag = k.replace("-", "_") + "_" + which
            out.append(arr("kF_" + tag, F, "short") + arr("kT_" + tag, T, fmt=lambda v: flt(v, "%.9g")) + arr("kL_" + tag, L, "short") + arr("kR_" + tag, R, "short"))
            out.append(arr("kV_" + tag, V) + arr("kS_" + tag, S, "int"))
    out.append("struct Model { const short* f; const float* t; const short* l; const short* r; const float* v; const int* s; int trees; float offset, rate; };\n")
    out.append("struct Pair { const char* a; const char* b; float auc; Model run, check; };\n")
    out.append("static const Pair kPairs[] = {\n")
    for k in pairs:
        p = cj["pairs"][k]
        a, b = k.split("-")
        ms = []
        for which in ("run", "check"):
            tag = k.replace("-", "_") + "_" + which
            m = p[which]
            ms.append("{kF_%s,kT_%s,kL_%s,kR_%s,kV_%s,kS_%s,%d,%s,%s}" % (tag, tag, tag, tag, tag, tag, len(m["trees"]), flt(m["offset"]), flt(m["rate"])))
        out.append('   {"%s","%s",%s,%s,%s},\n' % (a, b, flt(p["auc"]), ms[0], ms[1]))
    if not pairs:
        out.append('   {"","",0.0f,{},{}},\n')
    out.append("};\nconstexpr int kNumPairs = %d;\n" % len(pairs))
    # parity: the run model's P for fixed lane settings on grid points (no interpolation), so the engine's walk can be checked
    par = []
    for (i, si, di), (j, sj, dj) in PARITY:
        a, b = cell(grids[i], LANES[i][0], si, di), cell(grids[j], LANES[j][0], sj, dj)
        k = LANES[i][0] + "-" + LANES[j][0]
        m = cj["pairs"].get(k, {}).get("run")
        par.append(-1.0 if m is None or k not in pairs else score(m, pr.pair_features(pr.vec(a), pr.vec(b))))
    out.append("// (lane, semis, decay) pairs, transient 0, and the run model's P\n")
    out.append("static const float kParityIn[][6] = {%s};\n" % ",".join("{%d,%d,%s,%d,%d,%s}" % (i, si, flt(di), j, sj, flt(dj)) for (i, si, di), (j, sj, dj) in PARITY))
    out.append(arr("kParityP", par) + "} // namespace compat\n")
    dst = os.path.join(ROOT, "src/app/graph/GenerateSamplesCompat.inc")
    open(dst, "w").write("".join(out))
    print("%d strong pairs exported: %s -> %s (%d KB)" % (len(pairs), ", ".join(pairs), dst, os.path.getsize(dst) // 1024))


if __name__ == "__main__":
    main()
