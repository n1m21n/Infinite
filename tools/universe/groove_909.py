#!/usr/bin/env python3
"""909 patterns and MPC / SP-1200 swing for the Drums part (PLAN-2026-10-30 item 17).
Reads the Drumazon 2 pattern library (.dr2seq, plain XML, 16 steps per lane at 1/16) and the swing percents in the names of
Ableton's MPC 3000 and SP 1200 16th swing grooves, and writes GenerateSamplesGrooves909.inc:
  kGroove909[]   unique 16-step figures, lanes k s h o c (BD; SD; CH, or RD when CH is empty; OH; CP), four = BD on 0 4 8 12
  kSwing909[]    the machines' 16th swings in DrumSequencer units: odd 16ths move by swing * 0.5 steps, so p% is 4p/100 - 2
    groove_909.py [--patterns DIR] [--swing DIR] [--out FILE] [--stats]
groove_bank.py's inc is left alone; SampleStyles.cpp draws from both."""
import argparse, glob, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.expanduser("~/Infinite/musical_datasets/2_grooves_rhythm")
DEFAULT_OUT = os.path.join(HERE, "..", "..", "src", "app", "graph", "GenerateSamplesGrooves909.inc")


def lanes(path):
    """Lane name -> steps for a straight 1/16 pattern, or None (triplets, empty)."""
    t = open(path, encoding="utf-8", errors="replace").read()
    if 'modifier="Triplet"' in t or 'rate="1/16"' not in t:
        return None
    return dict(re.findall(r'<([A-Z]{2}) steps="([^"]*)"', t))


def hits(s):
    return "".join("x" if c in "Oo" else "." for c in s)


def figures(L):
    """16-step figures from one pattern: a 32-step pattern gives both halves."""
    n = len(L.get("BD", ""))
    if n not in (16, 32):
        return []
    out = []
    for o in range(0, n, 16):
        g = {k: hits(L.get(k, "." * n)[o:o + 16]) for k in ("BD", "SD", "CH", "OH", "CP", "RD")}
        h = g["CH"] if "x" in g["CH"] else g["RD"]
        f = (g["BD"], g["SD"], h, g["OH"], g["CP"])
        if "x" in f[0] and "x" in f[2]:  # a groove needs a kick and a hat; fills and intros are left out
            out.append(f)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--patterns", default=os.path.join(DATA, "drumazon2_patterns"))
    ap.add_argument("--swing", default=os.path.join(DATA, "ableton_grooves", "Swing"))
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--stats", action="store_true")
    a = ap.parse_args()
    seen, figs = set(), []
    for p in sorted(glob.glob(os.path.join(a.patterns, "*.dr2seq"))):
        L = lanes(p)
        for f in figures(L) if L else []:
            if f not in seen:
                seen.add(f); figs.append(f)
    four = lambda f: all(f[0][i] == "x" for i in (0, 4, 8, 12))
    sw = {}
    for sub, name in (("MPC", "MPC 3000"), ("SP 1200", "SP 1200")):
        for p in glob.glob(os.path.join(a.swing, sub, "Swing %s 16ths *.agr" % name)):
            pct = int(re.search(r"16ths (\d+)\.agr$", p).group(1))
            sw.setdefault(round(4 * pct / 100 - 2, 2), []).append("%s %d%%" % (name, pct))
    if a.stats:
        print("%d figures (%d four-on-the-floor), swings %s" % (len(figs), sum(map(four, figs)), sorted(sw)))
        return
    L = ["// Generated by tools/universe/groove_909.py from the Drumazon 2 909 pattern library and the swing percents of",
         "// Ableton's MPC 3000 / SP 1200 16th swing grooves. x a hit (the 909's accent is not kept), . a rest.",
         "// Lanes: kick, snare, closed hat (ride when the pattern has no closed hat), open hat, clap. Do not edit by hand.",
         "struct Groove909 { bool four; const char* k; const char* s; const char* h; const char* o; const char* c; };",
         "static const Groove909 kGroove909[] = {"]
    for f in sorted(figs, key=lambda f: (not four(f), f)):
        L.append('   { %s, "%s", "%s", "%s", "%s", "%s" },' % ("true" if four(f) else "false", *f))
    L += ["};", "// DrumSequencer swing (odd 16ths late by swing * 0.5 steps) for each machine setting: 4p/100 - 2",
          "static const float kSwing909[] = { %s };" % ", ".join("%.2ff" % v for v in sorted(sw)) + "  // " +
          "; ".join("%.2f %s" % (v, ", ".join(sorted(sw[v]))) for v in sorted(sw)), ""]
    open(a.out, "w").write("\n".join(L))
    print("wrote %s: %d figures (%d four-on-the-floor), %d swings" % (os.path.normpath(a.out), len(figs), sum(map(four, figs)), len(sw)))


if __name__ == "__main__":
    main()
