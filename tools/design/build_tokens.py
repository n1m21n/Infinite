#!/usr/bin/env python3
"""tokens.json -> Tokens.gen.h. Usage: build_tokens.py [--check]  (--check fails if the header is stale)."""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "src/app/ui/design/tokens.json"
OUT = ROOT / "src/app/ui/design/Tokens.gen.h"

def ident(s): return s.replace(".", "_")

def build():
    t = json.loads(SRC.read_text())
    L = ["// GENERATED by tools/design/build_tokens.py from tokens.json. Do not edit.",
         "#pragma once", "", "namespace tok", "{"]
    b = t["base"]
    for group in ("space", "radius", "type", "icon", "pin"):
        for k, v in b[group].items():
            L.append(f"   constexpr float {group}_{k} = {float(v)}f;")
    for k, v in b["motion_ms"].items():
        L.append(f"   constexpr float motion_{k} = {float(v)}f;")
    L.append(f"   constexpr float hit_min = {float(b['hit_min'])}f;")
    L.append(f"   constexpr float bar_h = {float(b['bar_h'])}f;")
    L.append(f"   constexpr float tile = {float(b['tile'])}f;")
    r = t["roles"]
    L += ["", "   struct Rgba8 { unsigned char r, g, b, a; };", "   struct Rgbaf { float r, g, b, a; };", "   struct Pair8 { Rgba8 dark, light; };", "   struct Pairf { Rgbaf dark, light; };"]
    # Colour roles are `inline` variables (not constexpr) so a user theme can override them at run time
    # (src/app/ui/ThemeFiles.cpp). d_<name> holds the build-time default; kColorTokens maps "dotted.name" -> both.
    reg = []
    for k, v in r["pairs"].items():
        d, l = v["dark"], v["light"]
        init = f"{{ {{{d[0]}, {d[1]}, {d[2]}, {d[3]}}}, {{{l[0]}, {l[1]}, {l[2]}, {l[3]}}} }}"
        L.append(f"   inline const Pair8 d_{ident(k)} = {init};")
        L.append(f"   inline Pair8 {ident(k)} = d_{ident(k)};")
        reg.append((k, "Pair8", ident(k)))
    for k, v in r.get("fixed", {}).items():
        L.append(f"   inline const Rgba8 d_{ident(k)} = {{{v[0]}, {v[1]}, {v[2]}, {v[3]}}};")
        L.append(f"   inline Rgba8 {ident(k)} = d_{ident(k)};")
        reg.append((k, "Rgba8", ident(k)))
    for k, v in r["pairs_f"].items():
        d, l = v["dark"], v["light"]
        f = lambda c: "{" + ", ".join(f"{x}f" for x in c) + "}"
        L.append(f"   inline const Pairf d_{ident(k)} = {{ {f(d)}, {f(l)} }};")
        L.append(f"   inline Pairf {ident(k)} = d_{ident(k)};")
        reg.append((k, "Pairf", ident(k)))
    L += ["", "   enum class ColorKind { Pair8, Rgba8, Pairf };",
          "   struct ColorToken { const char* name; ColorKind kind; void* value; const void* def; };",
          "   inline const ColorToken kColorTokens[] = {"]
    for k, kind, i in reg:
        L.append(f'      {{ "{k}", ColorKind::{kind}, &{i}, &d_{i} }},')
    L += ["   };", f"   inline constexpr int kColorTokenCount = {len(reg)};", ""]
    for k, v in r["accent_ladder"].items():
        L.append(f"   constexpr float accent_{k} = {v}f;")
    L += ["", "   namespace pal", "   {"]
    for k, v in t.get("palette", {}).items():
        L.append(f"      constexpr Rgba8 {k} = {{{v[0]}, {v[1]}, {v[2]}, {v[3]}}};")
    L += ["   }", "", "   namespace palf", "   {"]
    for k, v in t.get("palette_f", {}).items():
        L.append(f"      constexpr Rgbaf {k} = {{{v[0]}f, {v[1]}f, {v[2]}f, {v[3]}f}};")
    L += ["   }", "}", ""]
    return "\n".join(L)

def doc():
    t = json.loads(SRC.read_text()); r = t["roles"]
    hx = lambda c: "#%02X%02X%02X%02X" % tuple(c) if len(c) == 4 and max(c) > 1 else "#%02X%02X%02X%02X" % tuple(round(x * 255) for x in c)
    L = ["# Theme token keys (generated)", "",
         "GENERATED by `tools/design/build_tokens.py` from `src/app/ui/design/tokens.json`. Do not edit.", "",
         "Keys of the `tokens` section of a theme JSON (see [themes.md](themes.md)). Values are `#RRGGBB` / `#RRGGBBAA`;",
         "a pair role also accepts `{\"dark\": ..., \"light\": ...}`.", "",
         "| Key | Kind | Default dark | Default light |", "|---|---|---|---|"]
    for k, v in r["pairs"].items(): L.append(f"| `{k}` | pair | `{hx(v['dark'])}` | `{hx(v['light'])}` |")
    for k, v in r["pairs_f"].items(): L.append(f"| `{k}` | pair | `{hx(v['dark'])}` | `{hx(v['light'])}` |")
    for k, v in r.get("fixed", {}).items(): L.append(f"| `{k}` | fixed | `{hx(v)}` | same |")
    return "\n".join(L) + "\n"

DOC = ROOT / "docs/theme-tokens.md"

if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("Tokens.gen.h is stale: run tools/design/build_tokens.py"); sys.exit(1)
        if not DOC.exists() or DOC.read_text() != doc():
            print("docs/theme-tokens.md is stale: run tools/design/build_tokens.py"); sys.exit(1)
        print("Tokens.gen.h up to date")
    else:
        OUT.write_text(text); DOC.write_text(doc()); print("wrote", OUT.relative_to(ROOT), DOC.relative_to(ROOT))
