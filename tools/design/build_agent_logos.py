#!/usr/bin/env python3
"""Embed the chat agents' official logos (art/brand/agents) into src/app/ui/design/AgentLogos.gen.h.

The files are the vendors' own files, copied unchanged (sources and rules: art/brand/agents/README.md).
Bytes, not string literals, so MSVC's 16 KB literal limit never bites. Run after changing a file there.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "art" / "brand" / "agents"
OUT = ROOT / "src" / "app" / "ui" / "design" / "AgentLogos.gen.h"

# name in the header -> file
FILES = [
    ("kClaude", "claude-spark-clay.svg"),
    ("kOpenAiBlack", "openai-blossom-black.svg"),
    ("kOpenAiWhite", "openai-blossom-white.svg"),
    ("kGeminiPng", "gemini-spark-512.png"),
]


def main():
    lines = [
        "// Generated by tools/design/build_agent_logos.py from art/brand/agents - do not edit.",
        "// The vendors' official logo files, unchanged; see art/brand/agents/README.md for sources and usage rules.",
        "#pragma once",
        "#include <cstddef>",
        "namespace agentlogos",
        "{",
    ]
    for name, file in FILES:
        data = (SRC / file).read_bytes()
        lines.append(f"   // {file}")
        lines.append(f"   inline constexpr unsigned char {name}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("   " + ",".join(f"0x{b:02x}" for b in data[i : i + 24]) + ",")
        lines.append("   };")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
