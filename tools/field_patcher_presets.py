#!/usr/bin/env python3
"""Extract every Field node's kPresets table into one C++ header.

field-patcher-check (tools/field_patcher_check.cpp) round-trips every shipped
preset through the box graph without building the app. The presets live in
the node sources, which pull in the whole app, so this script reads the
tables as text and writes them out as plain data.

Usage: field_patcher_presets.py <repo-root> <out-header>

Each table entry is `{ name, code }`, except Field Primitive's, which is
`{ name, topology, defaultCount, code }`. The name is the first string group
of an entry and the code is the last; adjacent string literals are one group,
exactly as C++ concatenates them. Literals are copied through verbatim, so no
escape is ever re-encoded.
"""
import re
import sys
from pathlib import Path

# host, file stem, domain used to compile the round trip, counts toward M3
HOSTS = [
    ("Notes", "FieldNotesNode", "notes", True),
    ("Primitive", "FieldPrimitiveNode", "element", True),
    ("Element", "FieldElementNode", "element", True),
    ("Pixel", "FieldPixelNode", "pixel", False),
    ("Sample", "FieldSampleNode", "sample", False),
    ("Synth", "FieldSynthNode", "sample", False),
    ("Graph", "FieldGraphNode", "graph", False),
]

TOKEN = re.compile(
    r'(?P<ws>\s+)'
    r'|(?P<lcomment>//[^\n]*)'
    r'|(?P<bcomment>/\*.*?\*/)'
    r'|(?P<str>"(?:\\.|[^"\\])*")'
    r'|(?P<punct>[{},])'
    r'|(?P<other>[^\s{},"/]+|/)',
    re.S,
)


def tokens(text):
    for m in TOKEN.finditer(text):
        kind = m.lastgroup
        if kind in ("ws", "lcomment", "bcomment"):
            continue
        yield kind, m.group(kind)


def table_text(src, path):
    start = src.find("static const std::vector<Preset> kPresets")
    if start < 0:
        sys.exit(f"{path}: no kPresets table")
    brace = src.index("{", src.index("=", start))
    end = src.index("return kPresets;", brace)
    return src[brace:end]


def entries(text, path):
    """Yield (name_literal, code_literal) for each top-level `{ ... }` entry."""
    depth = 0
    items = []      # string groups of the current entry
    group = None    # current run of adjacent literals
    out = []
    for kind, tok in tokens(text):
        if kind == "punct" and tok == "{":
            depth += 1
            if depth == 2:
                items, group = [], None
            continue
        if kind == "punct" and tok == "}":
            if depth == 2:
                if group is not None:
                    items.append(group)
                if len(items) < 2:
                    sys.exit(f"{path}: entry with fewer than two strings")
                out.append((" ".join(items[0]), " ".join(items[-1])))
            depth -= 1
            if depth == 0:
                break
            continue
        if depth != 2:
            continue
        if kind == "str":
            if group is None:
                group = []
            group.append(tok)
        else:
            if group is not None:
                items.append(group)
                group = None
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    root = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    lines = [
        "// Generated by tools/field_patcher_presets.py. Do not edit.",
        "#pragma once",
        "",
        "namespace FieldPatcherPresets",
        "{",
        "   struct Preset { const char* host; const char* domain; bool countsForM3; const char* name; const char* code; };",
        "   static const Preset kAll[] = {",
    ]
    total = 0
    for host, stem, domain, m3 in HOSTS:
        path = root / "src" / "nodes" / f"{stem}.cpp"
        src = path.read_text(encoding="utf-8")
        for name, code in entries(table_text(src, path), path):
            lines.append(f'      {{ "{host}", "{domain}", {"true" if m3 else "false"}, {name},')
            lines.append(f"        {code} }},")
            total += 1
    lines += ["   };", "}", ""]
    text = "\n".join(lines)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    if not out_path.exists() or out_path.read_text(encoding="utf-8") != text:
        out_path.write_text(text, encoding="utf-8")
    print(f"field_patcher_presets: {total} presets -> {out_path}")


if __name__ == "__main__":
    main()
