#!/usr/bin/env python3
"""Every node's own words, for the agent's node finder (src/core/chat/NodeFinder.cpp).

Asks the app to describe every node type, then writes src/core/chat/NodeVocab.gen.h: per type its category and the
words its controls use (param labels and keys, menu choices, button labels) and its in-app help text. The finder reads it next to the node
guide cards, so a new node or param is findable by its own words with no hand-written synonyms, and a node with no
guide card is still found.

  python3 scripts/node_vocab.py                 # describes with build-dev's app
  python3 scripts/node_vocab.py --from dump.json  # a saved {type: describe result} dump
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "core", "chat", "NodeVocab.gen.h")
APP = os.path.join(ROOT, "build-dev", "Infinite.app", "Contents", "MacOS", "Infinite")

# Control words that every node shares say nothing about which node fits.
SKIP = {"on", "off", "a", "b", "mix", "amount", "x", "y", "z", "w", "h", "the", "and", "of", "to", "in", "free", "none",
        "enabled", "enable", "show", "value", "type", "mode", "level", "out", "in", "input", "output", "p", "id", "seed",
        "reset", "trigger", "sync", "synced", "speed", "volume", "gain", "scale", "size", "position", "pos"}


def describe_all(app):
    cats = json.loads(subprocess.run([app, "--cli", "nodes"], capture_output=True, text=True, check=True).stdout)
    types = sorted({t for names in cats.values() for t in names})
    out = {}
    for t in types:
        r = subprocess.run([app, "--cli", "describe", t], capture_output=True, text=True)
        try:
            d = json.loads(r.stdout)
        except ValueError:
            continue
        if d.get("types"):
            out[t] = d["types"][0]
    return out


def words_of(text):
    # camelCase and snake_case keys read as words: "envAmount" -> env amount, "rate_div" -> rate div.
    text = re.sub(r"([a-z])([A-Z])", r"\1 \2", text or "")
    for w in re.split(r"[^A-Za-z0-9]+", text.lower()):
        if len(w) >= 2 and not w.isdigit() and w not in SKIP:
            yield w


def vocab(entry):
    seen, out = set(), []

    def add(text):
        for w in words_of(text):
            if w not in seen:
                seen.add(w)
                out.append(w)

    for row in entry.get("rows", []):
        add(row.get("label"))
        add(row.get("key"))
        for opt in row.get("options") or []:
            add(opt if isinstance(opt, str) else str(opt))
    for a in entry.get("actions", []):
        add(a.get("label"))
    for pin in entry.get("inputs", []) + entry.get("outputs", []):
        add(pin.get("label"))
    return out


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--from", dest="src")
    ap.add_argument("--app", default=APP)
    args = ap.parse_args()
    data = json.load(open(args.src)) if args.src else describe_all(args.app)
    if len(data) < 100:
        sys.exit("node_vocab: only %d node types described; is the app built?" % len(data))
    lines = [
        "// Generated by scripts/node_vocab.py from `infinite describe` of every node type. Do not edit: run the script.",
        "// Each node's category, the words its own controls use and its help text, for chat::FindNodes and chat::NodeDoc.",
        "#pragma once",
        "",
        "namespace NodeVocab",
        "{",
        "   struct Entry",
        "   {",
        "      const char* type;",
        "      const char* category;",
        "      const char* words; // space-separated, lowercase",
        "      const char* help;  // the in-app help text (Menu > Help), English",
        "   };",
        "   inline constexpr Entry kEntries[] = {",
    ]
    for t in sorted(data):
        e = data[t]
        lines.append("      { %s, %s, %s, %s }," % (c_str(t), c_str(e.get("category", "")), c_str(" ".join(vocab(e))),
                                               c_str(e.get("help", ""))))
    lines += ["   };", "}", ""]
    open(OUT, "w").write("\n".join(lines))
    print("node_vocab: %d types -> %s" % (len(data), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
