"""Vendor SLOOP SMK (Felucca SMK, github.com/ChanceTheMaker/sloop-smk) into Synth REF.

Usage:  python -I scripts/synthref_vendor_sloop_smk.py <clone of sloop-smk> <generated headers dir>

Copies, byte for byte, the include closure of the firmware's own browser
engine (web/audio/sloop-smk-engine.c: the SMK runtime and SLOOP 2.8 core it
#includes) plus the licence files, keeping the upstream layout so the
engine's relative #includes work unmodified. The six felucca_*.h tables are
generated by the firmware's own sloop/tools/gen_*.py (tables, CC0 samples,
drum kits, FM6 patches, OFL font) and are copied from <generated headers dir>.

Never vendored: assets/icons.png, docs/panel.jpg and the Hugelton sample pack
(tools/gen_waves.py output), which LICENSING.md keeps "all rights reserved".
gen_samples.py yields a byte-identical felucca_samples.h without that pack
(the CC0 kit covers every drum role), and felucca_icons.h must be generated
from a blank 192x72 atlas (sloop/tools/icons.json names, no artwork): the
knob-card icons draw empty, everything else is intact.
"""
import hashlib
import re
import shutil
import subprocess
import sys
from datetime import date
from pathlib import Path

DEST = Path(__file__).resolve().parent.parent / "src" / "gpl" / "SynthRef" / "cores" / "sloop_smk"
ENTRY = "web/audio/sloop-smk-engine.c"
INCLUDE_DIRS = [".", "firmware/hal"]
GENERATED = ["felucca_drumkits.h", "felucca_fm6.h", "felucca_font.h", "felucca_icons.h", "felucca_samples.h",
             "felucca_tables.h"]
LICENCES = ["LICENSE", "LICENSING.md", "README.md", "sloop/LICENSE", "sloop/LICENSING.md"]
INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.M)


def closure(root: Path) -> list:
    seen, todo = set(), [root / ENTRY]
    while todo:
        f = todo.pop().resolve()
        if f in seen or not f.is_file():
            continue
        seen.add(f)
        for inc in INCLUDE.findall(f.read_text(encoding="utf-8", errors="replace")):
            if Path(inc).name in GENERATED:
                continue
            for base in [f.parent] + [root / d for d in INCLUDE_DIRS]:
                cand = (base / inc).resolve()
                if cand.is_file():
                    todo.append(cand)
                    break
    return sorted(p.relative_to(root.resolve()) for p in seen)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src, gen = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
    if not (src / ENTRY).is_file() or not all((gen / g).is_file() for g in GENERATED):
        print("need a sloop-smk clone and a folder with the six generated felucca_*.h")
        return 1
    commit = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    files = closure(src) + [Path(f) for f in LICENCES if (src / f).is_file()]
    for sub in ("upstream", "generated"):
        if (DEST / sub).exists():
            shutil.rmtree(DEST / sub)
    lines = []
    for rel in files:
        out = DEST / "upstream" / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src / rel, out)
        lines.append(f"| `upstream/{rel.as_posix()}` | `{hashlib.sha256(out.read_bytes()).hexdigest()[:16]}` |")
    (DEST / "generated").mkdir(parents=True)
    for g in GENERATED:
        shutil.copyfile(gen / g, DEST / "generated" / g)
        lines.append(f"| `generated/{g}` | `{hashlib.sha256((gen / g).read_bytes()).hexdigest()[:16]}` |")
    (DEST / "UPSTREAM.md").write_text(
        "# SLOOP SMK upstream\n\n"
        "Vendored by `scripts/synthref_vendor_sloop_smk.py`; do not edit files under `upstream/` or `generated/`.\n\n"
        "- Source: https://github.com/ChanceTheMaker/sloop-smk (branch integrate/sloop-2.6-smk)\n"
        f"- Commit: `{commit}` (its `sloop/` is SLOOP 2.8 from github.com/isod89/sloop-fm1 b77bf55)\n"
        f"- Vendored: {date.today().isoformat()}\n"
        "- Licences: GPL-3.0-only (SLOOP / Felucca, Leo Kuroshita and contributors; SMK port), Apache-2.0\n"
        "  (sloop/firmware/src/fm6_core.c, msfa), MIT (phys_dsp.c, phys_symp.c: DaisySP / Rings), OFL (font in\n"
        "  generated/felucca_font.h), CC0 (samples in generated/felucca_samples.h). See upstream/LICENSING.md.\n"
        "- Not vendored: the \"all rights reserved\" Felucca assets (icons.png, panel art, Hugelton sample pack).\n"
        "  generated/felucca_icons.h comes from a blank atlas, so the knob-card icons are empty.\n"
        "- generated/: the output of the firmware's own sloop/tools/gen_*.py (read before running, run with -I).\n\n"
        f"{len(lines)} files (SHA-256 prefix):\n\n| File | SHA-256 |\n|---|---|\n" + "\n".join(lines) + "\n",
        encoding="utf-8", newline="\n")
    print(f"vendored {len(files)} upstream files + {len(GENERATED)} generated headers from {commit}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
