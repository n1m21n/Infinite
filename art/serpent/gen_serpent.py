def sketch3d(nid, code, comment=None):
    return node("3D", "Sketch 3D", nid, f"  s code {esc(code)}\n", comment)


def smooth(nid, src):
    node("3D", "Normals", nid)
    wires.append(f"geo {nid} 0 {src}")
    return nid


def material(nid, src, body):
    node("3D", "Material", nid, body)
    wires.append(f"geo {nid} 0 {src}")
    return nid


def join(nid, srcs):
    node("3D", "Join Geometry", nid)
    for k, s in enumerate(srcs):
        wires.append(f"geo {nid} {k} {s}")
    return nid


