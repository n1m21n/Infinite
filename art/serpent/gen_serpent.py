#!/usr/bin/env python3
"""Generates serpent.inf: SERPENS-09, a cybernetic glass snake looped through a glass ring and
iridescent bubbles, on a Florax-style poster ground.

Moodboard picks: Florax (black ground, jade glass, red-pink bubbles, black vines, label card),
Eden (translucent shell with green core, ball chain), butterfly (acid green + chrome + lilac),
blobs (chrome metaball). Palette: jade #3FD08A, acid #B6F24A, chrome lilac #C9C3E6,
bubble coral #FF5A6E, ink #07090A.

Layout: 1080x1350 (4:5) poster. 12-col / 15-row grid, 54 px margin. Ring centre on the upper
third/golden line, head on the left third, tail exits lower right. Loop = 8 s.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
W, H = 1080, 1350
LOOP = 8.0  # seconds
BPM = 120   # LFO rateBeats: beats = seconds * 2

out = ["infinite-patch 1",
       "# SERPENS-09: cybernetic glass snake (generated by art/serpent/gen_serpent.py; edit the script, not this file)."]
N = [0]
wires, mods = [], []


def esc(code):
    return code.strip("\n").replace("\\", "\\\\").replace("\n", "\\n")


def node(cat, typ, nid, body="", comment=None):
    N[0] += 1
    if comment:
        out.append(comment)
    out.append(f"node {N[0]} {cat} {typ}\n  id {nid}\n{body}end")
    return nid


def M(dst, key, src, lo, hi, o=0):
    mods.append(f"mod {dst} {key} {src} {o} 0 1 0.5 {lo:.4f} {hi:.4f}")


# ---------------------------------------------------------------- shared snake maths (JS)
COMMON = r"""
// ---- shared snake rig: centreline spline, slither wave, radius profile, frames ----
param("slither", 0.09, 0, 0.3);     // side-wave amplitude
param("glide", 1, 0, 2);            // how fast plates travel along the body
var LOOP = 8.0;
var CP = [
  [ 1.85,-2.55,-1.2], [ 1.25,-2.05, 0.2], [ 0.10,-1.75, 0.75], [-0.95,-1.25, 0.25],
  [-1.05,-0.45,-0.55], [-0.15,-0.05,-0.95], [ 0.75, 0.25,-0.75], [ 0.42, 0.62,-0.15],
  [ 0.30, 0.70, 0.55], [-0.20, 0.95, 1.05], [-0.85, 1.35, 0.85], [-1.05, 1.85, 0.30]
];
function cr(p0, p1, p2, p3, u) {
  var u2 = u * u, u3 = u2 * u, o = [];
  for (var k = 0; k < 3; k++)
    o.push(0.5 * (2 * p1[k] + (-p0[k] + p2[k]) * u + (2 * p0[k] - 5 * p1[k] + 4 * p2[k] - p3[k]) * u2 + (-p0[k] + 3 * p1[k] - 3 * p2[k] + p3[k]) * u3));
  return o;
}
function spline(s) {               // s in [0,1], 0 = tail, 1 = head
  var n = CP.length - 1, f = Math.min(s * n, n - 1e-6), i = Math.floor(f), u = f - i;
  var p0 = CP[Math.max(i - 1, 0)], p1 = CP[i], p2 = CP[i + 1], p3 = CP[Math.min(i + 2, n)];
  return cr(p0, p1, p2, p3, u);
}
function sub(a, b) { return [a[0] - b[0], a[1] - b[1], a[2] - b[2]]; }
function add(a, b) { return [a[0] + b[0], a[1] + b[1], a[2] + b[2]]; }
function mul(a, k) { return [a[0] * k, a[1] * k, a[2] * k]; }
function dot(a, b) { return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]; }
function crs(a, b) { return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]; }
function nrm(a) { var l = Math.hypot(a[0], a[1], a[2]) || 1; return [a[0] / l, a[1] / l, a[2] / l]; }
// radius profile: thin tail, full body, neck pinch, head bulb, snout
function radius(s) {
  var r = 0.03 + 0.20 * Math.pow(Math.min(1, s / 0.55), 0.7);
  if (s > 0.86) { var h = (s - 0.86) / 0.14; r *= 1 - 0.22 * Math.sin(Math.min(h * 2.2, 1) * Math.PI); }
  if (s > 0.92) { var q = (s - 0.92) / 0.08; r *= 1 + 0.55 * Math.sin(q * Math.PI * 0.85); }
  if (s > 0.985) r *= Math.max(0.15, 1 - (s - 0.985) / 0.015 * 0.85);
  return r;
}
var RIG = null, RIGT = -1;
function rig(t, n) {               // n samples with parallel-transport frames, cached per frame
  if (RIG && RIGT === t && RIG.length === n + 1) return RIG;
  var ph = TAU * t / LOOP, pts = [], i;
  for (i = 0; i <= n; i++) pts.push(spline(i / n));
  var T = [], out = [];
  for (i = 0; i <= n; i++) T.push(nrm(sub(pts[Math.min(i + 1, n)], pts[Math.max(i - 1, 0)])));
  var Nn = nrm(crs(T[0], [0, 0, 1]));
  for (i = 0; i <= n; i++) {
    if (i > 0) { Nn = sub(Nn, mul(T[i], dot(Nn, T[i]))); Nn = nrm(Nn); }
    var Bn = crs(T[i], Nn), s = i / n;
    // slither: travelling side wave, damped at tail tip and where the body threads the ring
    var env = Math.min(1, s * 4) * (1 - 0.8 * Math.exp(-Math.pow((s - 0.66) / 0.07, 2))) * (1 - 0.7 * Math.max(0, (s - 0.9) / 0.1));
    var w = slither * env * Math.sin(TAU * s * 3.2 - ph);
    var lift = 0.5 * slither * env * Math.cos(TAU * s * 3.2 - ph);
    out.push({ p: add(add(pts[i], mul(Bn, w)), mul(Nn, lift)), T: T[i], N: Nn, B: Bn, s: s, r: radius(s) });
  }
  RIG = out; RIGT = t;
  return out;
}
// plate phase: segments travel tail->head over one loop
function plate(s, t) { return s * 34 - glide * 2 * t / LOOP * 2; }
function ringPt(f, a, rr) { var c = Math.cos(a), d = Math.sin(a); return add(f.p, add(mul(f.N, c * rr), mul(f.B, d * rr))); }
// loft a closed tube around the rig with radius fn(f, a)
function loft(R, M, rfn, i0, i1) {
  beginShape(QUADS);
  for (var i = i0; i < i1; i++) {
    var f0 = R[i], f1 = R[i + 1];
    for (var j = 0; j < M; j++) {
      var a0 = TAU * j / M, a1 = TAU * (j + 1) / M;
      var p00 = ringPt(f0, a0, rfn(f0, a0)), p01 = ringPt(f0, a1, rfn(f0, a1));
      var p11 = ringPt(f1, a1, rfn(f1, a1)), p10 = ringPt(f1, a0, rfn(f1, a0));
      vertex(p00[0], p00[1], p00[2], j / M, f0.s); vertex(p10[0], p10[1], p10[2], j / M, f1.s);
      vertex(p11[0], p11[1], p11[2], (j + 1) / M, f1.s); vertex(p01[0], p01[1], p01[2], (j + 1) / M, f0.s);
    }
  }
  endShape();
}
"""

# frame at any s (linear between rig samples), so plates glide smoothly
FRAME = r"""
function frameAt(R, s) {
  var n = R.length - 1, f = Math.max(0, Math.min(n - 1e-6, s * n)), i = Math.floor(f), u = f - i;
  var a = R[i], b = R[i + 1];
  function L(x, y) { return [x[0] + (y[0] - x[0]) * u, x[1] + (y[1] - x[1]) * u, x[2] + (y[2] - x[2]) * u]; }
  var T = nrm(L(a.T, b.T)), Nn = nrm(L(a.N, b.N));
  return { p: L(a.p, b.p), T: T, N: Nn, B: crs(T, Nn), s: s, r: a.r + (b.r - a.r) * u };
}
// body cross-section: a little wider than tall, flat belly
function xsec(f, a) { var c = Math.cos(a); return f.r * (1 + 0.10 * Math.sin(a) * Math.sin(a)) * (c < -0.3 ? 1 - 0.18 * (-c - 0.3) : 1); }
function strip(R, sa, sb, steps, M, rfn) {
  var F = [];
  for (var k = 0; k <= steps; k++) F.push(frameAt(R, sa + (sb - sa) * k / steps));
  beginShape(QUADS);
  for (var i = 0; i < steps; i++) {
    var f0 = F[i], f1 = F[i + 1];
    for (var j = 0; j < M; j++) {
      var a0 = TAU * j / M, a1 = TAU * (j + 1) / M;
      var p00 = ringPt(f0, a0, rfn(f0, a0, i / steps)), p01 = ringPt(f0, a1, rfn(f0, a1, i / steps));
      var p11 = ringPt(f1, a1, rfn(f1, a1, (i + 1) / steps)), p10 = ringPt(f1, a0, rfn(f1, a0, (i + 1) / steps));
      vertex(p00[0], p00[1], p00[2]); vertex(p01[0], p01[1], p01[2]);
      vertex(p11[0], p11[1], p11[2]); vertex(p10[0], p10[1], p10[2]);
    }
  }
  endShape();
}
var PLATES = 30, SPEED = 2;   // plates per body, plates travelled per loop
function plateRange(k, t) {   // s range of plate k (k may be fractional-shifted by time)
  var off = (SPEED * t / LOOP) % 1;
  return [(k + off) / PLATES, (k + off + 0.86) / PLATES];
}
"""

# armour: overlapping chrome-lilac scales, free edge toward the tail, gaps show the core
PLATESK = COMMON + FRAME + r"""
function draw(t) {
  var R = rig(t, 300);
  fill(0.86, 0.84, 0.96);
  for (var k = -1; k < PLATES; k++) {
    var rg = plateRange(k, t), sa = Math.max(0.06, rg[0]), sb = Math.min(0.885, rg[1]);
    if (sb - sa < 0.004) continue;
    strip(R, sa, sb, 7, 30, function (f, a, u) {
      var flare = 1.13 - 0.10 * u - 0.05 * Math.pow(Math.max(0, 1 - u * 6), 2);   // lip at the tail edge
      return xsec(f, a) * flare;
    });
  }
  // head: one smooth chrome capsule with a brow ridge
  strip(R, 0.885, 0.999, 30, 36, function (f, a, u) {
    var brow = 1 + 0.10 * Math.exp(-Math.pow((Math.cos(a) - 1) / 0.5, 2)) * Math.sin(u * PI);
    return xsec(f, a) * 1.1 * brow;
  });
}
"""

# glowing core seen in the plate gaps: acid-green vertebra chain
