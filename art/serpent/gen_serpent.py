# dorsal fins + jaw seam + tail spike (chrome)
CHROME = COMMON + FRAME + r"""
function draw(t) {
  var R = rig(t, 300);
  fill(0.86, 0.84, 0.96);
  for (var k = 0; k < PLATES; k++) {
    var rg = plateRange(k, t), sm = rg[0] + 0.25 / PLATES;
    if (sm < 0.18 || sm > 0.86) continue;
    var f = frameAt(R, sm);
    var base = add(f.p, mul(f.N, f.r * 1.05)), tip = add(f.p, add(mul(f.N, f.r * 1.75), mul(f.T, -f.r * 0.7)));
    tube(base[0], base[1], base[2], tip[0], tip[1], tip[2], f.r * 0.06, 10);
    push(); translate(tip[0], tip[1], tip[2]); sphere(f.r * 0.09, 12); pop();
  }
  // tail spike
  var f0 = frameAt(R, 0.06), tp = add(frameAt(R, 0).p, mul(f0.T, -0.25));
  tube(f0.p[0], f0.p[1], f0.p[2], tp[0], tp[1], tp[2], f0.r * 0.6, 12);
  push(); translate(tp[0], tp[1], tp[2]); sphere(0.02, 10); pop();
  // crown horns
  var hc = frameAt(R, 0.95);
  for (var b = -1; b <= 1; b += 2) {
    var base = add(hc.p, add(mul(hc.N, hc.r * 0.75), mul(hc.B, b * hc.r * 0.55)));
    var tip = add(base, add(mul(hc.T, -hc.r * 1.4), add(mul(hc.N, hc.r * 0.7), mul(hc.B, b * hc.r * 0.5))));
    tube(base[0], base[1], base[2], tip[0], tip[1], tip[2], hc.r * 0.07, 10);
    push(); translate(tip[0], tip[1], tip[2]); sphere(hc.r * 0.09, 10); pop();
  }
}
"""

# black cables: three vines that wrap the body in a slow helix (Florax black vines)
